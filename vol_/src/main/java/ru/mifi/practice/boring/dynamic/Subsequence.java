package ru.mifi.practice.boring.dynamic;

/**
 * Наибольшая общая подпоследовательность двух строк — не подстрока, а именно подпоследовательность:
 * символы идут в том же порядке, но не обязательно подряд. На ней держатся утилиты сравнения
 * файлов: строки, вошедшие в общую подпоследовательность, показываются неизменёнными, остальные —
 * удалёнными или добавленными.
 *
 * <p>Реализаций две, и разница между ними — в памяти. Табличная хранит всю матрицу размером n×m и
 * восстанавливает ответ обратным ходом по ней. Хиршберг хранит две строки матрицы, а ответ
 * добывает рекурсивным делением задачи — те же O(n·m) действий, но O(min(n,m)) памяти. На файлах
 * в миллион строк это разница между «не помещается» и «работает».
 */
@FunctionalInterface
public interface Subsequence {
    String longest(String left, String right);
}
