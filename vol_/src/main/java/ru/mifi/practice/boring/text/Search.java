package ru.mifi.practice.boring.text;

import java.util.List;
import java.util.Map;

/**
 * Поиск образцов в тексте: для каждого образца — позиции всех его вхождений, включая
 * перекрывающиеся.
 *
 * <p>Контракт нарочно взят сразу на набор образцов, а не на один: именно на наборе видна разница
 * между двумя способами. Рабин — Карп ищет каждый образец своим проходом по тексту, поэтому цена
 * растёт вместе с числом образцов. Ахо — Корасик собирает все образцы в один автомат и читает
 * текст ровно раз, сколько бы образцов ни искали.
 */
@FunctionalInterface
public interface Search {
    Map<String, List<Integer>> positions(String text, List<String> patterns);
}
