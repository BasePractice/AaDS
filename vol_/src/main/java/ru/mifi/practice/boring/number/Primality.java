package ru.mifi.practice.boring.number;

/**
 * Проверка числа на простоту. Реализаций две, и разница между ними — вся суть темы: перебор
 * делителей отвечает наверняка, но за время порядка корня из числа, а тест Миллера — Рабина
 * отвечает за десяток умножений, пожертвовав абсолютной уверенностью.
 *
 * <p>Общий контракт позволяет сверить их между собой на малых числах, где обе работают, и
 * увидеть, что на больших остаётся только вторая.
 */
@FunctionalInterface
public interface Primality {
    boolean prime(long number);
}
