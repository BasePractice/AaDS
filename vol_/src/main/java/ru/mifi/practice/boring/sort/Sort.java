package ru.mifi.practice.boring.sort;

/**
 * Сортировка целых чисел. Все реализации в этом пакете отвечают одним и тем же контрактом:
 * получают массив, возвращают новый упорядоченный и не трогают исходный. Поэтому их можно
 * подставлять одну вместо другой и сравнивать между собой на одних и тех же данных.
 *
 * <p>В пакете собраны сортировки, которых нет в основной программе курса: улучшения вставок и
 * пузырька промежутками, сортировка по разрядам без единого сравнения и сортирующая сеть,
 * рассчитанная на параллельное железо.
 */
@FunctionalInterface
public interface Sort {
    int[] sorted(int[] values);
}
