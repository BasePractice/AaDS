package ru.mifi.practice.boring.number;

/**
 * Умножение квадратных матриц. Реализаций две: тройной цикл по определению и алгоритм Штрассена.
 * Общий контракт нужен, чтобы сверять их между собой: Штрассен считает то же самое, но другим
 * набором действий, и легко ошибиться в одном из семи произведений, не заметив этого.
 *
 * <p>Матрица здесь — обычный двумерный массив; сторона у обоих сомножителей одна и та же.
 */
@FunctionalInterface
public interface MatrixProduct {
    int[][] product(int[][] left, int[][] right);
}
