package ru.mifi.practice.boring.text;

/**
 * Фонетический код слова: слова, которые звучат похоже, получают одинаковый код. Нужен там, где
 * поиск идёт по фамилиям и названиям, записанным на слух: «Смирнов» и «Смирнофф» отличаются
 * буквами, но не звучанием, и точное сравнение строк тут бесполезно.
 *
 * <p>Реализаций две, обе для латиницы: Soundex сводит слово к букве и трём цифрам по таблице
 * согласных, Metaphone работает правилами над сочетаниями букв и потому различает больше.
 */
@FunctionalInterface
public interface Phonetic {
    String code(String word);
}
