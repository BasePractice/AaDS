package ru.mifi.practice.boring.number;

/**
 * Проверка простоты перебором делителей — то, что придумывает каждый, впервые услышав задачу.
 * Делители перебираются до корня из числа: если у числа есть делитель больше корня, то есть и
 * парный ему меньше, иначе их произведение превысило бы само число.
 *
 * <p>Двойка и тройка проверяются отдельно, а дальше шаг идёт по числам вида 6k±1: все остальные
 * делятся на два или на три и уже отсеяны. Это срезает две трети работы, но не меняет главного —
 * цена остаётся порядка корня из числа, то есть растёт экспоненциально с длиной записи числа.
 *
 * <p>Зато ответ точен всегда, и потому этот класс годится в эталоны для проверки вероятностного
 * теста.
 */
public final class TrialDivision implements Primality {

    @Override
    public boolean prime(long number) {
        if (number < 2) {
            return false;
        }
        if (number % 2 == 0 || number % 3 == 0) {
            return number == 2 || number == 3;
        }
        for (long divisor = 5; divisor * divisor <= number; divisor += 6) {
            if (number % divisor == 0 || number % (divisor + 2) == 0) {
                return false;
            }
        }
        return true;
    }
}
