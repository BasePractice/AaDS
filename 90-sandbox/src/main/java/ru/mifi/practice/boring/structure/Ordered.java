package ru.mifi.practice.boring.structure;

import java.util.OptionalInt;

/**
 * Упорядоченное множество целых чисел: хранит числа без повторов и умеет отвечать не только
 * «есть ли такое», но и «а какое следующее» — на этом вопросе обычная хеш-таблица бессильна.
 *
 * <p>Контракт один, реализаций три, и в этом весь смысл пакета: декартово дерево держит порядок
 * деревом со случайными приоритетами, список с пропусками — этажами связных списков, а
 * X-быстрый бор — битами числа и хеш-таблицами по уровням. Задача одна, устройство разное, и
 * сравнивать их можно напрямую, подставляя одну вместо другой.
 *
 * <p>Числа, а не произвольные ключи, потому что бор работает с битами: сравнимость ему мало,
 * ему нужна фиксированная ширина числа.
 */
public interface Ordered {

    void add(int value);

    void remove(int value);

    boolean contains(int value);

    /** Наименьшее из хранимых чисел, строго большее заданного. */
    OptionalInt next(int value);

    /** Наибольшее из хранимых чисел, строго меньшее заданного. */
    OptionalInt previous(int value);

    int size();

    default boolean isEmpty() {
        return size() == 0;
    }
}
