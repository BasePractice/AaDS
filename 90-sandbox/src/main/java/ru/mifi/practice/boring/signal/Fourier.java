package ru.mifi.practice.boring.signal;

/**
 * Дискретное преобразование Фурье: раскладывает сигнал на частоты и собирает обратно. Реализаций
 * две — по определению и быстрая, — и общий контракт позволяет сверить их между собой. Ответы
 * обязаны совпадать с точностью до погрешности вещественной арифметики; расходятся они только
 * временем: O(n²) против O(n log n).
 */
public interface Fourier {

    /** Из сигнала в частоты. */
    Complex[] direct(Complex[] signal);

    /** Из частот обратно в сигнал. */
    Complex[] inverse(Complex[] spectrum);
}
